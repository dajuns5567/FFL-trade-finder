const short=name=>String(name||'').trim().split(/\s+/).filter(Boolean).at(-1)||String(name||'team');

function refine(team){
  const a=team?.inquirer_article;if(!a)return team;
  const s=short(team?.team_name);
  const players=(a.sections||[]).find(x=>String(x?.kind||'')==='players');
  if(players&&Array.isArray(players.paragraphs)){
    const starters=(team?.starter_details||[]).filter(x=>x?.name);
    players.paragraphs=players.paragraphs.map(p=>{
      let text=String(p||'');
      if(!/artificial spotlight|beyond its four leading scorers/i.test(text))return text;
      const player=starters.find(x=>text.includes(String(x.name)));
      const name=player?.name||'That depth player';
      return text
        .replace(/That is worth carrying into Week 3 because it shows what the lineup received after its leading scorers, not because a fourth name needs artificial spotlight\./gi,`${name} gave ${s} scoring depth behind the leaders; Week 3 will show whether that depth holds.`)
        .replace(/That matters here because it shows what the lineup received beyond its four leading scorers and helps separate a top-heavy result from a more balanced one\./gi,`${name} gave ${s} scoring depth behind the leaders; Week 3 will show whether that depth holds.`);
    });
  }
  a.paragraphs=(a.sections||[]).flatMap(x=>x?.paragraphs||[]).filter(Boolean);
  a.structure_revision='week2-r100';
  return team;
}

export function applyWeek2EditorialR16(raw){
  const out=applyR99(raw);
  if(!out||Number(out.season)!==2026||Number(out.week)!==2)return out;
  out.teams=(out.teams||[]).map(refine);
  out.structure_revision='week2-r100';
  if(out.league_overview)out.league_overview.structure_revision='week2-r100';
  return out;
}
