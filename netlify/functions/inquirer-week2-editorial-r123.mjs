function fixScheduleSentence(text){
  let m;
  if((m=text.match(/^After this matchup, (.+?) comes next and (.+?) follows\.$/))){
    const [,one,two]=m;
    return `Week 3 comes first; a win there would ease the pressure before the schedule moves to ${one} and then ${two}.`;
  }
  if((m=text.match(/^Then the schedule turns to (.+?), with (.+?) waiting behind it\.$/))){
    const [,one,two]=m;
    return `Handle Week 3 first; then the schedule turns to ${one}, with ${two} behind it.`;
  }
  if((m=text.match(/^Beyond Week 3, the next two dates are (.+?) and (.+?)\.$/))){
    const [,one,two]=m;
    return `Week 3 deserves the first attention; beyond it, the next two dates are ${one} and ${two}.`;
  }
  if((m=text.match(/^The road after Week 3 runs through (.+?) before (.+?)\.$/))){
    const [,one,two]=m;
    return `Week 3 sets the next mood; after that, the road runs through ${one} before ${two}.`;
  }
  return text;
}

function refine(team){
  const article=team?.inquirer_article;if(!article)return team;
  const outlook=(article.sections||[]).find(s=>String(s?.kind||'')==='outlook');
  if(outlook&&Array.isArray(outlook.paragraphs)){
    outlook.paragraphs=outlook.paragraphs.map(p=>String(p||'').split(/(?<=[.!?])\s+/).map(fixScheduleSentence).join(' '));
  }
  article.paragraphs=(article.sections||[]).flatMap(section=>section?.paragraphs||[]).filter(Boolean);
  article.structure_revision='week2-r123';
  return team;
}

export function applyWeek2EditorialR16(raw){
  const out=applyR122(raw);
  if(!out||Number(out.season)!==2026||Number(out.week)!==2)return out;
  out.teams=(out.teams||[]).map(refine);
  out.structure_revision='week2-r123';
  if(out.league_overview)out.league_overview.structure_revision='week2-r123';
  return out;
}
