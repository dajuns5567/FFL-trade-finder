function refine(team){
  const a=team?.inquirer_article;if(!a)return team;
  for(const s of a.sections||[]){
    if(!Array.isArray(s?.paragraphs))continue;
    s.paragraphs=s.paragraphs.map(p=>String(p||'').replace(/\b([A-Z][A-Za-z'.-]+) may keep the praise if the same role survives a second examination\./g,`$1's next test is whether the same role survives a second examination.`));
  }
  a.paragraphs=(a.sections||[]).flatMap(s=>s?.paragraphs||[]).filter(Boolean);
  a.structure_revision='week2-r87';
  return team;
}

