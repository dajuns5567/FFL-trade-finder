function refine(team){
  const a=team?.inquirer_article;if(!a)return team;
  const players=(a.sections||[]).find(x=>String(x?.kind||'')==='players');
  if(players&&Array.isArray(players.paragraphs)){
    const starters=(team?.starter_details||[]).filter(x=>x?.name);
    players.paragraphs=players.paragraphs.map(p=>{
      let text=String(p||'');
      const player=starters.find(x=>text.includes(String(x.name)))||starters.find(x=>{
        const last=String(x.name).trim().split(/\s+/).at(-1);
        return last&&new RegExp(`\\b${last.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}\\b`).test(text);
      });
      if(!player)return text;
      const last=String(player.name).trim().split(/\s+/).at(-1);
      return text
        .replace(/\bHis 2025 average was /g,`${last}'s 2025 average was `)
        .replace(/\bThe fantasy result finished ([0-9.]+) points (above|below) projection\./g,`${last}'s fantasy result finished $1 points $2 projection.`)
        .replace(/\bSnap share moved from ([^.]*)\./g,`${last}'s snap share moved from $1.`);
    });
  }
  a.paragraphs=(a.sections||[]).flatMap(x=>x?.paragraphs||[]).filter(Boolean);
  a.structure_revision='week2-r99';
  return team;
}

export function applyWeek2EditorialR16(raw){
  const out=applyR98(raw);
  if(!out||Number(out.season)!==2026||Number(out.week)!==2)return out;
  out.teams=(out.teams||[]).map(refine);
  out.structure_revision='week2-r99';
  if(out.league_overview)out.league_overview.structure_revision='week2-r99';
  return out;
}
