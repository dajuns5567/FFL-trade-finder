// One-time replacement-site cutover gate. This helper never creates or
// modifies a Blob; it verifies the two genuine pre-Week-5 locked editions.
const DESKS=['lede','players','management','hot-seat','cool-throne','value','sentiment','outlook'];
const RECAP=['lead','standings','players','decisions','league','outlook'];
function lockedEdition(edition,week){
 const teams=edition?.teams||[];
 return edition?.available===true&&edition?.published_locked===true&&
  Number(edition?.season)===2026&&Number(edition?.week)===week&&
  Array.isArray(teams)&&teams.length===32&&
  new Set(teams.map(t=>String(t?.roster_id||''))).size===32&&
  teams.every(t=>t?.roster_id!=null&&t?.inquirer_article?.headline)&&
  !!edition?.league_overview?.headline;
}
export function verifiedReplacementHistory(week3,week4){
 if(!lockedEdition(week3,3)||!lockedEdition(week4,4))
  return{ready:false,reason:'Original 2026 Weeks 3 and 4 are not both complete, locked editions'};
 // Week 4 is the approved frozen editorial baseline, NOT a simulated
 // recreation or a more recent malformed Week 5 generated by older code.
 const week4Desks=(week4.teams||[]).every(t=>{
  const kinds=(t?.inquirer_article?.sections||[]).map(x=>x?.kind);
  return kinds.length===DESKS.length&&DESKS.every(x=>kinds.includes(x));
 });
 const recap=week4?.league_overview?.sections||[];
 const blocks=recap[0]?.blocks||[];
 const approvedRecap=recap.length>=4&&blocks.length===RECAP.length&&
  RECAP.every((kind,i)=>blocks[i]?.kind===kind);
 if(!week4Desks||!approvedRecap)
  return{ready:false,reason:'Restored Week 4 does not match the approved eight-desk / six-beat editorial baseline'};
 return{ready:true,reason:'Original locked 2026 Weeks 3-4 verified for replacement-site bootstrap'};
}