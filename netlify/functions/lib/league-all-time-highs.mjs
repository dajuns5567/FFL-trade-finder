// Durable, monotonic per-award, per-roster historical records.
// Never replace an actual first-observed timestamp with the timestamp of a
// later read or a losing score. Invalid/incomplete candidates cannot erase data.
export function validAwardHigh(row){
 const key=String(row?.award_key||''),roster=String(row?.roster_id||'');
 const score=row?.score==null?NaN:Number(row.score);
 return /^[a-z0-9-]+(?::[a-z0-9-]+)*$/.test(key)&&
   /^[1-9][0-9]*$/.test(roster)&&Number.isFinite(score)&&
   Math.abs(score)<1e8&&score!==-999999&&
   !/not enough data|unavailable|loading/i.test(String(row?.detail||''));
}
export function mergeAwardHighs(existing=[],observations=[],observedAt=new Date().toISOString()){
 if(!Number.isFinite(Date.parse(observedAt)))throw Error('Invalid award observation date');
 const byKey=new Map();
 const merge=(row,source)=>{
  if(!validAwardHigh(row))return;
  const key=String(row.award_key)+'|'+String(row.roster_id);
  const score=Number(row.score),current=byKey.get(key);
  if(current&&score<current.score)return;
  if(current&&score===current.score){
   // The same peak may exist in both Netlify Blob and the independent
   // GitHub archive. Retain the EARLIEST verified observation timestamp.
   if(source==='historical'&&Number.isFinite(Date.parse(row.captured_at))&&
      new Date(row.captured_at)<new Date(current.captured_at))
    byKey.set(key,{...current,captured_at:String(row.captured_at)});
   return;
  }
  const captured_at=source==='historical'&&Number.isFinite(Date.parse(row.captured_at))
   ?String(row.captured_at):observedAt;
  byKey.set(key,{award_key:String(row.award_key),roster_id:String(row.roster_id),score,
   detail:String(row.detail||''),captured_at});
 };
 // Preserve the highest existing record independently of input order.
 for(const row of existing||[])merge(row,'historical');
 for(const row of observations||[])merge(row,'observation');
 return [...byKey.values()].sort((a,b)=>a.award_key.localeCompare(b.award_key)||
  Number(a.roster_id)-Number(b.roster_id));
}
export function highObservationsFromStandings(awards){
 if(!Array.isArray(awards))return[];
 const adjusted=new Set(['fleecer','fleeced','deal-maker','efficiency','big-swing',
  'trade-average','volume-wins','big-regret','balanced']);
 return awards.flatMap(award=>{
  const key=String(award?.key||'');
  const award_key=adjusted.has(key)?key+':trade-adjusted-v1':key;
  return (award?.standings||[]).map(r=>({
   award_key,roster_id:String(r?.roster_id||''),score:r?.score,detail:r?.detail
  })).filter(validAwardHigh);
 });
}

// A one-time authenticated preview export can seed the independent GitHub
// archive without falsely claiming it was generated by the headless scheduler.
// Never trust an arbitrary JSON or incomplete import just because its source
// label matches. Scheduled canonical archives remain the normal successor.
export function verifiedDurableAwardHighRecords(data,leagueId){
 if(data?.schema_version!==1||String(data?.league_id)!==String(leagueId)||
    !Array.isArray(data?.records)||data.records.length<500)return[];
 const bootstrap=data.source==='github-verified-netlify-blob-bootstrap';
 if(!bootstrap&&data.source!=='github-canonical-headless-all-time-highs')return[];
 if(bootstrap){
  const evidence=data.import_provenance;
  if(evidence?.source!=='ffl-verified-netlify-blob-all-time-highs-readback'||
     !/^https:\/\/deploy-preview-\d+--animated-dasik-3de74a\.netlify\.app$/.test(String(evidence?.preview_origin||''))||
     Number(evidence?.blob_record_count)!==data.records.length||
     !Number.isFinite(Date.parse(evidence?.exported_at))||
     data.latest_observation_at!==evidence.exported_at)
   return[];
 }
 const keys=new Set(),categories=new Set(),rosters=new Set();
 for(const row of data.records){
  if(!validAwardHigh(row)||!Number.isFinite(Date.parse(row?.captured_at))||
     Date.parse(row.captured_at)>Date.now()+60000||
     bootstrap&&Date.parse(row.captured_at)>Date.parse(data.latest_observation_at)+60000)
   return[];
  const key=String(row.award_key)+'|'+String(row.roster_id);
  if(keys.has(key))return[];
  keys.add(key);categories.add(String(row.award_key));
  rosters.add(String(row.roster_id));
 }
 if(categories.size!==20||rosters.size!==32)return[];
 return data.records;
}


/**
 * Canonical independently captured highs, NOT historical one-off snapshots.
 *
 * A 639-row legacy Blob export can preserve real values and timestamps yet
 * still represent just ONE uncorroborated observation. Never silently promote
 * those old peaks to certified records merely by changing the archive source
 * label. Only this distinct verified_records ledger is eligible for the
 * user-facing historical leaderboard.
 */
export function verifiedCanonicalHighRecords(data,leagueId){
 if(data?.schema_version!==1||
    String(data?.league_id)!==String(leagueId)||
    data.source!=='github-canonical-headless-all-time-highs'||
    !/^[a-f0-9]{40}$/i.test(String(data.source_commit||''))||
    String(data.canonical_fingerprint||'').length<5||
    !Number.isFinite(Date.parse(data.latest_observation_at))||
    !Array.isArray(data.verified_records)||data.verified_records.length<500||
    !['idp-v96-single-source-continuous-v95-evidence',
      'idp-v101-verified-role-growth-v100-source-free-lineage'].includes(String(data.model_used||'')))
   return [];
 const eligible=verifiedDurableAwardHighRecords(data,leagueId);
 if(eligible.length!==data.records.length)return [];
 const archive=new Map(eligible.map(row=>[row.award_key+'|'+row.roster_id,row]));
 const keys=new Set(),categories=new Set(),rosters=new Set();
 for(const row of data.verified_records){
  if(!validAwardHigh(row)||!Number.isFinite(Date.parse(row.captured_at))||
     Date.parse(row.captured_at)>Date.parse(data.latest_observation_at)+60000)return [];
  const key=row.award_key+'|'+row.roster_id,raw=archive.get(key);
  if(keys.has(key)||!raw||Number(raw.score)+0.000001<Number(row.score))return [];
  keys.add(key);categories.add(row.award_key);rosters.add(String(row.roster_id));
 }
 return categories.size===20&&rosters.size===32?data.verified_records:[];
}
